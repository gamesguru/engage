mod exit_code {
    //! Exit codes the program uses.

    /// Success.
    ///
    /// This is used instead of [`ExitCode::SUCCESS`][0] because that's subject
    /// to change based on the platform and we don't want our error exit codes
    /// to overlap with it.
    ///
    /// [0]: std::process::ExitCode::SUCCESS
    pub(crate) const SUCCESS: u8 = 0;

    /// A process failed to run.
    pub(crate) const PROCESS_ERROR: u8 = 1;

    /// The error was generated by Engage itself.
    pub(crate) const INTERNAL_ERROR: u8 = 2;
}

use name::Name;
use observability::prelude as o;

#[tokio::main]
async fn main() -> ExitCode {
    let Err(e) = try_main().await else {
        return ExitCode::from(exit_code::SUCCESS);
    };

    // Clap prints a good error message when it's the source of the error.
    if !matches!(e, error::Main::Cli) {
        execute!(
            stderr(),
            Print(error::report::report(iter::once(&e))),
            Print("\n"),
        )
        .expect("should be able to write to stderr");
    }

    match e {
        error::Main::RunGraph(_) => ExitCode::from(exit_code::PROCESS_ERROR),
        _ => ExitCode::from(exit_code::INTERNAL_ERROR),
    }
}

/// Fallible version of [`main`].
async fn try_main() -> Result<(), error::Main> {
    use error::Main as E;

    let cancelled = Arc::new(Notify::new());

    let _ctrl_c_handle = AbortOnDropHandle::new(tokio::spawn({
        let cancelled = cancelled.clone();
        async move {
            loop {
                tokio::signal::ctrl_c()
                    .await
                    .expect("should be able to receive ctrl+c signals");
                o::warn!("cancellation requested");
                cancelled.notify_waiters();
            }
        }
    }));

    let args = match cli::try_parse() {
        Ok(x) => x,
        Err(e) => {
            e.print().expect("should be able to print message");

            if matches!(
                e.kind(),
                ErrorKind::DisplayHelp | ErrorKind::DisplayVersion
            ) {
                return Ok(());
            }

            return Err(E::Cli);
        }
    };

    let longest_name = Arc::new(OnceLock::new());

    observability::init(longest_name.clone(), args.log_format())
        .map_err(E::Observability)?;

    match args {
        cli::Args::Run {
            file,
            processes,
            ..
        } => run(cancelled, longest_name, file.as_deref(), processes).await,

        cli::Args::Dot {
            file,
            processes,
        } => dot(file.as_deref(), processes).await,

        cli::Args::List {
            file,
        } => list(file.as_deref()).await,

        cli::Args::Completions {
            shell,
        } => {
            clap_complete::generate(
                shell,
                &mut cli::command(),
                env!("CARGO_PKG_NAME"),
                &mut stdout(),
            );

            Ok(())
        }
    }
}

/// Run a graph, or a subgraph created from the selected `processes`.
async fn run(
    cancelled: Arc<Notify>,
    longest_name: Arc<OnceLock<usize>>,
    file: Option<&Path>,
    processes: Vec<Box<Name>>,
) -> Result<(), error::Main> {
    use error::Main as E;

    let processes = dedup_processes(processes).map_err(E::ProcessesRepeated)?;

    let (config, root_dir) = config::load(file).await.map_err(E::LoadConfig)?;

    longest_name
        .set(
            config
                .processes
                .keys()
                .map(|x| AsRef::<str>::as_ref(x).len())
                .max()
                .unwrap_or(0),
        )
        .expect("value should not be set yet");

    let graph = graph::build(&config.processes).map_err(E::BuildGraph)?;

    let graph = if processes.is_empty() {
        graph
    } else {
        graph::subgraph(&graph, &processes).map_err(E::ProcessesNotFound)?
    };

    graph::ensure_acyclic(&graph).map_err(E::Cyclic)?;

    run::run_graph(cancelled, Arc::new(graph), root_dir.into())
        .await
        .map_err(E::RunGraph)
}

/// Print a graph in Graphviz' DOT language of processes and their dependencies.
async fn dot(
    file: Option<&Path>,
    processes: Vec<Box<Name>>,
) -> Result<(), error::Main> {
    use error::Main as E;

    let processes = dedup_processes(processes).map_err(E::ProcessesRepeated)?;

    let (config, _) = config::load(file).await.map_err(E::LoadConfig)?;
    let graph = graph::build(&config.processes).map_err(E::BuildGraph)?;

    let graph = if processes.is_empty() {
        graph
    } else {
        graph::subgraph(&graph, &processes).map_err(E::ProcessesNotFound)?
    };

    // Print the graph.
    execute!(stdout(), Print(Dot::new(&graph)))
        .expect("should be able to write to stdout");

    Ok(())
}

/// List available processes.
async fn list(file: Option<&Path>) -> Result<(), error::Main> {
    use error::Main as E;

    let (config, _) = config::load(file).await.map_err(E::LoadConfig)?;

    for name in config.processes.keys() {
        println!("{name}");
    }

    Ok(())
}

/// Deduplicate a list of processes into a set.
fn dedup_processes(
    xs: Vec<Box<Name>>,
) -> Result<BTreeSet<Box<Name>>, BTreeSet<error::ProcessRepeated>> {
    use error::ProcessRepeated as E;

    let mut oks = BTreeSet::new();
    let mut errs = BTreeSet::new();

    for x in xs {
        if oks.contains(&x) {
            errs.insert(E(x));
        } else {
            oks.insert(x);
        }
    }

    if !errs.is_empty() {
        return Err(errs);
    }

    Ok(oks)
}
